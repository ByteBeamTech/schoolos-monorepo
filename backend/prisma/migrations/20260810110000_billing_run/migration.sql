-- CreateIndex
CREATE INDEX "BillingRun_tenantId_branchId_periodLabel_idx" ON "BillingRun"("tenantId", "branchId", "periodLabel");

-- CreateIndex: the frozen §6 run-level idempotency rule, at the
-- database level -- an active run blocks a second active run for the
-- same scope; a terminal one does not.
CREATE UNIQUE INDEX "BillingRun_active_scope_unique"
  ON "BillingRun" ("tenantId", "branchId", "periodLabel")
  WHERE "status" NOT IN ('COMPLETED', 'FAILED');

